print("ID SPECIFICATION AUDIT")
print("=" * 60)

# Test 1: Atomicity
print("\n[TEST 1] Atomicity of time.time_ns()")
print("-" * 60)
print("Claim: 'Atomic operations only'")

print("\nImplementation:")
print("  d = datetime.date.today().strftime('%Y%m%d')")
print("  micros_of_day = time.time_ns() // 1000 % 1_000_000_000")
print("  secrets.token_hex(2)")

print("\nAnalysis:")
print("  * time.time_ns(): Python built-in, reads system clock")
print("    - Returns uint64 (nanoseconds since epoch)")
print("    - CPU operation: atomic at CPU level")
print("    - OS syscall: single call = atomic read")
print("    - Verdict: ✓ Atomic")
print()
print("  * // 1000: Integer division (nanosec -> microsec)")
print("    - Single CPU arithmetic")
print("    - Verdict: ✓ Atomic")
print()
print("  * % 1_000_000_000: Modulo normalization")
print("    - Single CPU arithmetic")
print("    - But value is WRONG (see TEST 4)")
print()
print("  * secrets.token_hex(2): Random generation")
print("    - Separate syscall (os.urandom)")
print("    - NOT atomic with time.time_ns()")
print("    - Between time() and random(): clock can advance")
print("    - Verdict: ✗ NOT atomic as complete operation")

print("\n[TEST 2] Monotonicity claims")
print("-" * 60)
print("Claim: 'Monotonic microseconds'")
print()
print("Reality:")
print("  * Within a single process: time.time_ns() is monotonic")
print("  * Across processes: time.time_ns() is NOT compared")
print("  * Clock backward scenario: NOT handled")
print()
print("Verdict: ✓ Monotonic for single-process use case")
print("        ✗ NOT fail-closed if system clock changes")

print("\n[TEST 3] Collision probability")
print("-" * 60)
print("Model: time-based + random")
print()
print("Components:")
print("  - Time µs: 9 digits = 1,000,000,000 combinations")
print("  - Random: 4 hex chars = 65,536 combinations")
print()
print("Collision scenarios:")
print()
print("  Scenario A: Different microseconds")
print("    - IDs CANNOT collide")
print("    - Probability: 0%")
print()
print("  Scenario B: Same microsecond, different random")
print("    - IDs CANNOT collide (different random)")
print("    - Probability: 0%")
print()
print("  Scenario C: Same microsecond AND same random")
print("    - IDs COLLIDE")
print("    - P(same µs for 2 IDs) = depends on generation rate")
print("    - P(same random | same µs) = 1/65,536")
print()
print("At observed rate (34,552 IDs/sec from stress test):")
print("  - Rate = 34,552 IDs/sec ÷ 1,000,000 µs/sec = 0.034552 IDs/µs")
print("  - = 1 ID per ~28.95 µs")
print("  - Probability 2 IDs in same µs = ~7%")
print("  - Expected collision rate = 7% × (1/65,536) = 0.000107%")
print()
print("Verdict: ✗ Collisions ARE theoretically possible (probability > 0)")
print("        ✓ But VERY rare (1 in 1 million+)")
print()
print("'Zero collision risk' claim = INCORRECT / MISLEADING")

print("\n[TEST 4] Modulo operation correctness")
print("-" * 60)
seconds_per_day = 86400
micros_per_day = seconds_per_day * 1_000_000
modulo_used = 1_000_000_000
modulo_correct = 86_400_000_000

print(f"Microseconds per day: {micros_per_day}")
print()
print(f"Code uses: % {modulo_used}")
print(f"  - Wraps at: {modulo_used / micros_per_day:.1f} days")
print(f"  - ⚠ WRONG: Should wrap at 1 day, not {modulo_used / micros_per_day:.1f} days")
print()
print(f"Should use: % {modulo_correct}")
print(f"  - Wraps at: {modulo_correct / micros_per_day:.1f} days")
print(f"  - ✓ CORRECT: Wraps at exactly 1 day")
print()
print("Example impact:")
today = time.time_ns() // 1000
mod_wrong = today % 1_000_000_000
mod_right = today % 86_400_000_000
print(f"  Current µs since epoch: {today}")
print(f"  With % 1e9: {mod_wrong}")
print(f"  With % 86.4e9: {mod_right}")
print()
print("Verdict: ✗ CRITICAL: Modulo value is wrong")
print("        The 9-digit field will NOT reset daily")
print("        It will reset every 11.6 days instead")

print("\n[TEST 5] System clock adjustment handling")
print("-" * 60)
